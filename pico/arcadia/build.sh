#!/usr/bin/env bash
# build.sh -- assemble the Arcadia console clients with Macroassembler AS.
#
# Usage: ./build.sh [client ...]        default: fujitest fujiboot fujicfg
#
# Output: build/<client>.bin, 8192 bytes (fujibank: 8K + 3 APPBANK pages). p2bin emits a
# $0000-$2FFF flat that tools/mkimage.py folds into the image; the "FUJI" claim is
# stamped at image 0x1CFC.
#
# fujiboot takes its target from the environment:
#   BOOT_HOST=0 BOOT_PATH=/game.bin ./build.sh fujiboot
#
# AS: asl on PATH, then ~/asl (CI), then the Windows binaries under wine.

set -euo pipefail
cd "$(dirname "$0")"

CLAIM_OFF=$((0x1CFC))

AS_BIN="${AS_BIN:-$HOME/Workspace/o2workspace/bin}"
if command -v asl >/dev/null 2>&1; then
    AS=asl P2BIN=p2bin
elif [ -x "$HOME/asl/asl" ]; then
    AS="$HOME/asl/asl" P2BIN="$HOME/asl/p2bin"
else
    AS="wine $AS_BIN/asw.exe" P2BIN="wine $AS_BIN/p2bin.exe"
    export WINEDEBUG=-all
fi

mkdir -p build

# Regenerated every run so a stale target cannot survive an environment change.
gen_bootcfg() {
    {
        echo "; generated by build.sh -- do not edit"
        echo "BOOTHST EQU     ${BOOT_HOST:-0}"
        printf 'BOOTPTH:DB      "%s"\n' "${BOOT_PATH:-/fujitest.bin}"
        echo "        DB      0"
    } > build/bootcfg.inc
}

build_one() {
    local name=$1
    [ "$name" = fujiboot ] && gen_bootcfg
    # AS resolves INCLUDE against the cwd, so assemble from testrom/.
    (cd testrom && $AS -q -L "$name.asm")
    mv "testrom/$name.p" "build/$name.p"
    mv -f "testrom/$name.lst" "build/$name.lst" 2>/dev/null || true
    local pages=0
    [ "$name" = fujibank ] && pages=3
    $P2BIN "build/$name.p" "build/$name.flat" \
        -r "\$0000-\$$(printf '%04X' $((0x3000 + pages * 0x800 - 1)))" -l 0
    if [ "$pages" -gt 0 ]; then
        python3 tools/mkimage.py --pages "$pages" "build/$name.flat" "build/$name.bin"
    else
        python3 tools/mkimage.py "build/$name.flat" "build/$name.bin"
    fi
    printf 'FUJI' | dd of="build/$name.bin" bs=1 seek=$CLAIM_OFF \
        conv=notrunc status=none
    rm -f "build/$name.p" "build/$name.flat"
    python3 tools/checkrom.py "build/$name.bin"
}

clients=("$@")
[ ${#clients[@]} -eq 0 ] && clients=(fujitest fujiboot fujicfg)
for client in "${clients[@]}"; do
    build_one "$client"
done
