# graft.lib.sh -- the steps every cart's emu/apply.sh shares to put the cartridge's own
# sources into a MAME tree. Source it from the emu directory, after
# `cd "$(dirname "$0")"`, with MAME set; the cart's driver and slot edits stay its own.

FUJI_COMMON=../../common
GRAFTED=()          # every file put into the tree, for graft_lua
GRAFTED_COMMON=()   # the pico/common modules among them, for graft_fujins

# graft DIR FILE...  copy each FILE into DIR. A .c goes in as .cpp: MAME forces a C++
# precompiled header on its sources, and the shared sources build both ways.
graft() {
    local dir=$1 f name
    shift
    for f in "$@"; do
        name=$(basename "$f")
        case $name in
        *.c) rm -f "$dir/$name"; name=${name%.c}.cpp ;;
        esac
        cp "$f" "$dir/$name"
        GRAFTED+=("$name")
    done
}

# graft_common DIR MODULE...  pico/common's MODULE.c and MODULE.h, from src/ and include/
# or from emu/
graft_common() {
    local dir=$1 m f found
    shift
    for m in "$@"; do
        found=
        for f in "$FUJI_COMMON/src/$m.c" "$FUJI_COMMON/emu/$m.c" \
                 "$FUJI_COMMON/include/$m.h" "$FUJI_COMMON/emu/$m.h"; do
            if [ -f "$f" ]; then
                graft "$dir" "$f"
                found=1
            fi
        done
        [ -n "$found" ] || { echo "apply.sh: pico/common has no $m" >&2; exit 1; }
        GRAFTED_COMMON+=("$m")
    done
}

# graft_fujins DIR PREFIX [FILE...] [-- SYMBOL...]  write DIR/fujins.h, renaming every
# symbol fujins.syms lists for a grafted common module, and each SYMBOL, to PREFIX_name,
# and put it first in those modules and each FILE. Several carts' copies of one source
# then share a MAME binary, each built against its own fuji_mailbox.h.
graft_fujins() {
    local dir=$1 prefix=$2 files=() syms=() m line f sym
    shift 2
    while [ $# -gt 0 ] && [ "$1" != -- ]; do
        files+=("$1")
        shift
    done
    [ $# -eq 0 ] || shift
    for m in "${GRAFTED_COMMON[@]}"; do
        if line=$(grep "^$m " "$FUJI_COMMON/emu/fujins.syms"); then
            # shellcheck disable=SC2206 # the list is words
            syms+=(${line#* })
            files+=("$m.cpp" "$m.h")
        fi
    done
    syms+=("$@")
    {
        echo "/* GENERATED by pico/$(basename "$(dirname "$PWD")")/emu/apply.sh -- do not edit. */"
        echo "#ifndef $(echo "$prefix" | tr a-z A-Z)_FUJINS_H"
        echo "#define $(echo "$prefix" | tr a-z A-Z)_FUJINS_H"
        for sym in "${syms[@]}"; do
            echo "#define $sym ${prefix}_$sym"
        done
        echo "#endif"
    } > "$dir/fujins.h"
    GRAFTED+=(fujins.h)
    for f in "${files[@]}"; do
        if ! head -1 "$dir/$f" | grep -q fujins.h; then
            printf '#include "fujins.h"\n%s\n' "$(cat "$dir/$f")" > "$dir/$f.tmp"
            mv "$dir/$f.tmp" "$dir/$f"
        fi
    done
}

# graft_lua BUSDIR ANCHOR  list every grafted file in scripts/src/bus.lua, after
# src/devices/bus/BUSDIR/ANCHOR, unless it is there already, so a file added to a graft
# later still reaches a tree grafted before.
graft_lua() {
    python3 - "$MAME/scripts/src/bus.lua" "$1" "$2" "${GRAFTED[@]}" <<'EOF'
import sys
path, busdir, anchor, files = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
text = open(path).read()
line = '\t\tMAME_DIR .. "src/devices/bus/%s/%%s",\n' % busdir
if line % anchor not in text:
    sys.exit("apply.sh: bus.lua anchor line not found")
missing = "".join(line % f for f in dict.fromkeys(files) if line % f not in text)
if missing:
    open(path, "w").write(text.replace(line % anchor, line % anchor + missing, 1))
    print("apply.sh: bus.lua updated (build with REGENIE=1)")
EOF
}
