#!/usr/bin/env python3
"""mkromh.py -- pack the client a cart serves at power-on into fujiconfigrom.h.

    mkromh.py [checks] client > build/gen/fujiconfigrom.h

Checks, each a refusal to bake the wrong file:
    --size N          exactly N bytes
    --blocks N        a whole number of N-byte blocks
    --claim OFF       "FUJI" at OFF (negative counts from the end)
    --expect OFF:TXT  TXT at OFF
    --strip-a78       drop a 128-byte .a78 header first
"""
import argparse
import sys


def main():
    ap = argparse.ArgumentParser(usage="mkromh.py [checks] client")
    ap.add_argument("client")
    ap.add_argument("--size", type=lambda s: int(s, 0))
    ap.add_argument("--blocks", type=lambda s: int(s, 0))
    ap.add_argument("--claim", type=lambda s: int(s, 0))
    ap.add_argument("--expect", action="append", default=[])
    ap.add_argument("--strip-a78", action="store_true")
    args = ap.parse_args()

    data = open(args.client, "rb").read()
    if args.strip_a78 and len(data) >= 128 and data[1:10] == b"ATARI7800":
        data = data[128:]

    def refuse(why):
        sys.exit("mkromh: %s: %s" % (args.client, why))

    if args.size is not None and len(data) != args.size:
        refuse("%d bytes, not %d" % (len(data), args.size))
    if args.blocks and (not data or len(data) % args.blocks):
        refuse("%d bytes, not a whole number of %d-byte blocks" % (len(data), args.blocks))
    want = [(args.claim, b"FUJI")] if args.claim is not None else []
    for e in args.expect:
        off, _, txt = e.partition(":")
        want.append((int(off, 0), txt.encode()))
    for off, sig in want:
        at = off if off >= 0 else len(data) + off
        if not 0 <= at <= len(data) - len(sig) or data[at:at + len(sig)] != sig:
            refuse("no %r at %#x" % (sig.decode(), at))

    print("/* fujiconfigrom.h -- GENERATED by mkromh.py from %s, do not edit. */"
          % args.client.split("/")[-1])
    print()
    print("#ifndef FUJICONFIGROM_H")
    print("#define FUJICONFIGROM_H")
    print()
    print("#define FUJI_CONFIGROM_SIZE %d" % len(data))
    print()
    print("static const unsigned char _configrom[FUJI_CONFIGROM_SIZE] = {")
    for i in range(0, len(data), 12):
        print("    " + " ".join("0x%02X," % b for b in data[i:i + 12]))
    print("};")
    print()
    print("#endif /* FUJICONFIGROM_H */")


if __name__ == "__main__":
    main()
