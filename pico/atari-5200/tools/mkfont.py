def rows(ch):
    if 'a' <= ch <= 'z':
        ch = ch.upper()
    src = G.get(ch, G['?'])
    out = []
    for r in src.split('|'):
        assert len(r) == 5, (ch, r)
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 0x40 >> i          # one blank column on the left
        out.append(v)
    out.append(0)                       # the eighth row is a blank baseline
    return out


def ascii_of(code):
    if code < 0x40:
        return code + 0x20
    if code < 0x60:
        return None
    return code


def main():
    print("; font.inc -- GENERATED by tools/mkfont.py, do not edit.")
    print("; 128 characters in ANTIC internal-code order, 8 rows each, top first.")
    for code in range(128):
        a = ascii_of(code)
        data = rows(chr(a)) if a is not None and a != 0x7F else (
            rows('\x7f') if a == 0x7F else [0] * 8)
        print("        .byte " + ",".join("$%02X" % b for b in data)
              + "   ; $%02X" % code)


if __name__ == "__main__":
    main()
