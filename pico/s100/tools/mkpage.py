#!/usr/bin/env python3
"""mkpage.py -- bake the boot page and the card's images into C headers.

    mkpage.py <outdir> <bootpage.asm> <config.bin> <loader.bin>

The page is assembled twice, for page FFh / pipe A0h (the S100_REF_* values)
and for FEh / A4h; every byte that moved by -1 is a page site, by +4 a pipe
site, and anything else is an error. Writes s100_bootpage.h and s100_images.h.
"""
import os
import re
import subprocess
import sys
import tempfile

Z80ASM = os.path.expanduser(os.environ.get("Z80ASM", "~/Workspace/z88dk/bin/z88dk-z80asm"))


def assemble(src, page, pipe, tmp):
    text = open(src).read()
    text = re.sub(r"^PAGE\s+EQU\s+\S+", "PAGE    EQU     0%02X00h" % page, text, flags=re.M)
    text = re.sub(r"^PIPE\s+EQU\s+\S+", "PIPE    EQU     0%02Xh" % pipe, text, flags=re.M)
    asm = os.path.join(tmp, "page%02x.asm" % page)
    open(asm, "w").write(text)
    out = os.path.join(tmp, "page%02x.bin" % page)
    subprocess.run([Z80ASM, "-m8080", "-b", "-o" + out, asm], check=True)
    data = open(out, "rb").read()
    if len(data) > 256:
        sys.exit("mkpage: the boot page is %d bytes, over 256" % len(data))
    return data + bytes(256 - len(data))


def carray(name, data):
    rows = [", ".join("0x%02X" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "static const uint8_t %s[%d] = {\n    %s,\n};\n" % (name, len(data), ",\n    ".join(rows))


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    out, src, config, loader = sys.argv[1:]
    with tempfile.TemporaryDirectory() as tmp:
        ref = assemble(src, 0xFF, 0xA0, tmp)
        alt = assemble(src, 0xFE, 0xA4, tmp)
    patches = []
    for i, (a, b) in enumerate(zip(ref, alt)):
        if a == b:
            continue
        if (b - a) & 0xFF == 0xFF:
            patches.append(("S100_PATCH_PAGE", i))
        elif (b - a) & 0xFF == 4:
            patches.append(("S100_PATCH_PIPE", i))
        else:
            sys.exit("mkpage: byte %d moved by %d, neither page nor pipe" % (i, b - a))

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "s100_bootpage.h"), "w") as f:
        f.write("/* Generated by tools/mkpage.py from client/bootpage.asm; do not edit. */\n")
        f.write("#ifndef S100_BOOTPAGE_H\n#define S100_BOOTPAGE_H\n#include \"s100_regs.h\"\n")
        f.write(carray("s100_boot_page", ref))
        f.write("static const s100_patch_t s100_boot_patches[%d] = {\n" % len(patches))
        f.write("".join("    {%s, %d},\n" % p for p in patches))
        f.write("};\n#define S100_BOOT_PATCH_COUNT %d\n#endif\n" % len(patches))

    cfg = open(config, "rb").read()
    ldr = open(loader, "rb").read()
    with open(os.path.join(out, "s100_images.h"), "w") as f:
        f.write("/* Generated by tools/mkpage.py; do not edit. */\n")
        f.write("#ifndef S100_IMAGES_H\n#define S100_IMAGES_H\n#include \"s100_regs.h\"\n")
        f.write(carray("s100_config_image", cfg))
        f.write(carray("s100_loader_image", ldr))
        f.write("static const s100_image_t s100_images[2] = {\n")
        f.write("    {s100_config_image, %d, 0x0100, 0x0100},\n" % len(cfg))
        f.write("    {s100_loader_image, %d, 0x4C00, 0x4C00},\n};\n" % len(ldr))
        f.write("#define S100_IMAGE_COUNT 2\n#endif\n")
    print("mkpage: %d patch sites, CONFIG %d bytes, loader %d bytes" % (len(patches), len(cfg), len(ldr)))


if __name__ == "__main__":
    main()
