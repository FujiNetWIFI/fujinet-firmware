def rows(ch):
    if 'a' <= ch <= 'z':
        ch = ch.upper()
    src = G.get(ch, G['?'])
    out = []
    for r in src.split('|'):
        assert len(r) == 5, (ch, r)
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 0x40 >> i          # one blank column on the left
        out.append(v)
    out.append(0)                       # the eighth row is a blank baseline
    return out


def main():
    print("; font.inc -- GENERATED by tools/mkfont.py, do not edit.")
    print("; 96 tiles for ASCII $20-$7F, plane 0 only, 8 rows each.")
    for c in range(0x20, 0x80):
        ch = chr(c)
        label = ch if 0x20 < c < 0x7F else '.'
        print("        .byte %s   ; $%02X '%s'"
              % (",".join("$%02X" % b for b in rows(ch)), c, label))


if __name__ == "__main__":
    main()
