#!/usr/bin/env python3
"""mkfontlua.py -- the font inverted (glyph to character) for the Lua harnesses.

The harnesses read the screen back to navigate by name. Lowercase is drawn as
uppercase, so decoding is lossy; harnesses compare names as rendered.

Usage: mkfontlua.py > emu/vcsfont.lua
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from vcsfont import glyph          # noqa: E402


def rank(ch):
    if ch.isdigit():
        return 0
    if ch.isupper():
        return 1
    if ch == ' ':
        return 2
    return 3


def main():
    best = {}
    for c in range(0x20, 0x80):
        ch = chr(c)
        if ch.islower():
            continue                      # folds to uppercase; never rendered
        rows = glyph(ch)
        key = 0
        for r in rows:
            key = (key << 3) | r
        if key not in best or rank(ch) < rank(best[key]):
            best[key] = ch

    print("-- GENERATED by tools/mkfontlua.py -- do not edit.")
    print("-- Glyph bitmap -> character, for decoding the rendered planes.")
    print("-- Key is the five 3-bit ink rows packed high-to-low.")
    print("local M = {}")
    print("M.glyph = {")
    for key in sorted(best):
        ch = best[key]
        lit = "'" + (ch if ch not in ("'", "\\") else "\\" + ch) + "'"
        print("  [%d] = %s," % (key, lit))
    print("}")
    print()
    print("-- Character -> glyph key: what a name looks like on screen.")
    print("-- Lowercase draws as uppercase, so names are compared as rendered.")
    print("M.key = {")
    for c in range(0x20, 0x80):
        ch = chr(c)
        if ch.islower():
            continue
        rows = glyph(ch)
        key = 0
        for r in rows:
            key = (key << 3) | r
        lit = "'" + (ch if ch not in ("'", "\\") else "\\" + ch) + "'"
        print("  [%s] = %d," % (lit, key))
    print("}")
    print("return M")


if __name__ == "__main__":
    main()
