def rows(ch):
    if 'a' <= ch <= 'z':
        ch = ch.upper()
    src = G.get(ch, G['?'])
    out = []
    for r in src.split('|'):
        assert len(r) == 5, (ch, r)
        v = 0
        for i, c in enumerate(r):
            if c == '#':
                v |= 0x40 >> i          # one blank column on the left
        out.append(v)
    out.append(0)                       # the eighth row is a blank baseline
    return out


def main():
    glyph = [rows(chr(c)) if 0x20 <= c < 0x80 else [0] * 8 for c in range(128)]
    print("; font.inc -- GENERATED by tools/mkfont.py, do not edit.")
    print("; 8 pages: page p is pixel row 7-p of characters $00-$FF.")
    for page in range(8):
        r = 7 - page
        data = [glyph[c][r] for c in range(128)] + [glyph[c][r] ^ 0xFF for c in range(128)]
        print("; row %d" % r)
        for i in range(0, 256, 16):
            print("        .byte " + ",".join("$%02X" % b for b in data[i:i + 16]))


if __name__ == "__main__":
    main()
