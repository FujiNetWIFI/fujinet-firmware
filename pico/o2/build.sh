#!/bin/bash
# Assemble the stub BIOS and cart images with Macroassembler AS.
set -e
AS_BIN="${AS_BIN:-$HOME/Workspace/o2workspace/bin}"
OUT="${OUT:-$PWD/build}"
mkdir -p "$OUT"

# Prefer a native AS (Debian/Ubuntu package "asl"), else the Windows binaries
# under $AS_BIN through wine.
if command -v asl >/dev/null 2>&1; then
  AS=asl; P2BIN=p2bin
elif command -v asw >/dev/null 2>&1; then
  AS=asw; P2BIN=p2bin
else
  AS="wine $AS_BIN/asw.exe"; P2BIN="wine $AS_BIN/p2bin.exe"
  export WINEDEBUG=-all
fi
run_as()    { ( cd "$OUT" && $AS "$@" ); }
run_p2bin() { ( cd "$OUT" && $P2BIN "$@" ); }

# stub BIOS: $000-$3FF
cp emu/stubbios.a48 "$OUT/"
run_as -q -L stubbios.a48
run_p2bin stubbios.p stubbios.bin -r 0x0-0x3FF -l 0

# Boot target for fujiboot; point it at a local file to validate the push path:
#   BOOT_HOST=0 BOOT_PATH=/fujitest.bin ./build.sh fujiboot
BOOT_HOST="${BOOT_HOST:-2}"
BOOT_PATH="${BOOT_PATH:-/K.C. Munchkin (USA).bin}"

# cart: $400-$FFF (3K)
cp testrom/*.a48 testrom/*.inc testrom/g7000.h "$OUT/"
echo "; GENERATED by build.sh, do not edit.
HOSTSLOT equ $BOOT_HOST" > "$OUT/bootcfg.inc"
printf '; GENERATED by build.sh, do not edit.\nbootpath:  db "%s",0\n' \
  "$BOOT_PATH" > "$OUT/bootpath.inc"
# APPBANK (protocol 2) images: one assembly per page with PAGE set, the fixed
# half ($400-$7FF) taken from page 0's, then every page's $800-$FFF in order.
APP_PAGES=4
build_appbank() {
  local b=$1 p parts=""
  for p in $(seq 0 $((APP_PAGES-1))); do
    printf '; GENERATED by build.sh, do not edit.\nPAGE equ %d\n    include "%s.a48"\n' \
      "$p" "$b" > "$OUT/${b}_p$p.a48"
    run_as -q -L "${b}_p$p.a48"
    run_p2bin "${b}_p$p.p" "${b}_pg$p.bin" -r 0x800-0xFFF -l 0
    python3 tools/checklayout.py "$OUT/${b}_p$p.lst"
    parts="$parts $OUT/${b}_pg$p.bin"
  done
  run_p2bin "${b}_p0.p" "${b}_fixed.bin" -r 0x400-0x7FF -l 0
  cat "$OUT/${b}_fixed.bin" $parts > "$OUT/$b.bin"
}

for src in "$@"; do
  b=$(basename "$src" .a48)
  case "$b" in
    app*) build_appbank "$b"; continue ;;
  esac
  run_as -q -L "$b.a48"
  run_p2bin "$b.p" "$b.bin" -r 0x400-0xFFF -l 0
  python3 tools/checklayout.py "$OUT/$b.lst"
done
ls -l "$OUT"/*.bin
